"""Writes Data/ForeverPetFood.lua: every food the Forever client says a pet
can eat, with its diet.

Run from the repository root:

    python tools/make_pet_food.py <tables folder> --build <build>

  <tables folder>   the Forever client's game tables as CSV (Item,
                    ItemSparse). Never commit the tables.

Item's ItemPetFoodID is the diet the game gives each item: 1 Meat, 2 Fish,
3 Cheese, 4 Bread, 5 Fungus, 6 Fruit. Data/PetFood.lua's hand list stays as
it is; the addon lays these over it, so where the two disagree the game's
diet wins. Left out: diets a Classic pet never names (7 and up), items with
no name or named "UNUSED ITEM", quest items (so a quest item is never fed)
and conjured food. A food on the hand list that the game says no pet eats
goes in NOT_FOOD, so it is not offered.

Never edit the output by hand: rerun the tool.
"""

import argparse
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Data" / "ForeverPetFood.lua"
HAND = ROOT / "Data" / "PetFood.lua"

DIETS = {1: "Meat", 2: "Fish", 3: "Cheese", 4: "Bread", 5: "Fungus", 6: "Fruit"}
QUEST_CLASS = "12"
CONJURED = 0x2            # ItemSparse Flags_0


def read_csv(folder, name):
    with open(folder / (name + ".csv"), encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def hand_ids(path=HAND):
    text = path.read_text(encoding="utf-8")
    return {int(m.group(1)): m.group(2)
            for m in re.finditer(r'\{\s*(\d+)\s*,\s*"((?:[^"\\]|\\.)*)"\s*\}', text)}


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build(items, sparse, hand):
    """(foods, not_food): foods is [(diet, id, name)], not_food [(id, name)]."""
    names, flags = {}, {}
    for row in sparse:
        item_id = int(row["ID"])
        names[item_id] = row.get("Display_lang") or ""
        flags[item_id] = int(row.get("Flags_0") or 0)
    foods, not_food = [], []
    for row in items:
        item_id = int(row["ID"])
        diet = DIETS.get(int(row.get("ItemPetFoodID") or 0))
        if not diet:
            if item_id in hand and int(row.get("ItemPetFoodID") or 0) == 0:
                not_food.append((item_id, hand[item_id]))
            continue
        name = names.get(item_id, "")
        if not name or name == "UNUSED ITEM":
            continue
        if row.get("ClassID") == QUEST_CLASS:
            continue
        if flags.get(item_id, 0) & CONJURED:
            continue
        foods.append((diet, item_id, name))
    order = list(DIETS.values())
    foods.sort(key=lambda f: (order.index(f[0]), f[1]))
    not_food.sort()
    return foods, not_food


def render(foods, not_food, build_name):
    out = [
        "-- Blackthornes Pets -- Data/ForeverPetFood.lua",
        "-- Every food the Forever client says a pet can eat, and its diet.",
        "--",
        "-- Generated by tools/make_pet_food.py from the Forever client's game",
        "-- tables (build %s). Never edit it by hand: rerun the tool." % build_name,
        "--",
        "-- FOOD[item ID] = { diet, English name }. Data/PetFood.lua lays these over",
        "-- its own list, so the game's diet wins. NOT_FOOD[item ID] = English name",
        "-- for a food on that list the game says no pet eats.",
        "",
        "local _, ns = ...",
        "",
        "ns.ForeverPetFood = {",
        "    FOOD = {",
    ]
    for diet, item_id, name in foods:
        out.append("        [%d] = { %s, %s }," % (item_id, lua_string(diet), lua_string(name)))
    out.append("    },")
    out.append("    NOT_FOOD = {")
    for item_id, name in not_food:
        out.append("        [%d] = %s," % (item_id, lua_string(name)))
    out.append("    },")
    out.append("}")
    return "\n".join(out) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("tables", type=Path)
    parser.add_argument("--build", required=True)
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args(argv)
    foods, not_food = build(read_csv(args.tables, "Item"), read_csv(args.tables, "ItemSparse"),
                            hand_ids())
    args.out.write_text(render(foods, not_food, args.build), encoding="utf-8", newline="\n")
    hand = hand_ids()
    new = sum(1 for _, item_id, _ in foods if item_id not in hand)
    print("%d foods (%d not on the hand list), %d on the hand list no pet eats"
          % (len(foods), new, len(not_food)))


if __name__ == "__main__":
    main()

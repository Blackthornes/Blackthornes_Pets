"""Writes Data/DemonBooks.lua: every rank of every warlock demon's skills,
the grimoire that teaches it, the warlock level it needs and what it costs.

Run from the repository root:

    python tools/make_demon_books.py <tables folder> --build <build>

  <tables folder>   the Forever client's game tables as CSV (SkillLine,
                    SkillLineAbility, CreatureFamily, SpellName, Spell,
                    SpellEffect, ItemSparse, ItemEffect, ItemXItemEffect).
                    Never commit the tables.

A grimoire is an item whose use teaches the demon a spell (spell effect 36).
Its price and level are the item's own. Ranks a demon starts with have no
grimoire. Where demon trainers stand is not in the tables: the addon learns
it when their window opens.

Never edit the output by hand: rerun the tool.
"""

import argparse
import collections
import csv
import re
from pathlib import Path

LEARN_PET_SPELL = 36     # the spell effect that teaches the pet a spell
STARTS_WITH = "2"        # SkillLineAbility.AcquireMethod: the demon has it from the start
DEMONS = ("Imp", "Voidwalker", "Succubus", "Felhunter")


def read_csv(folder, name):
    with open(folder / (name + ".csv"), encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def rank_of(text):
    m = re.search(r"(\d+)", text or "")
    return int(m.group(1)) if m else 1


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    p = argparse.ArgumentParser()
    p.add_argument("tables")
    p.add_argument("--build", required=True)
    args = p.parse_args()
    folder = Path(args.tables)
    repo = Path(__file__).resolve().parent.parent

    names = {r["ID"]: r["Name_lang"] for r in read_csv(folder, "SpellName")}
    subtext = {r["ID"]: r.get("NameSubtext_lang", "") for r in read_csv(folder, "Spell")}

    # The demons' skill lines, by the families that use them.
    line_names = {r["ID"]: r["DisplayName_lang"] for r in read_csv(folder, "SkillLine")}
    demon_of_line = {}
    families = collections.defaultdict(set)
    for demon in DEMONS:
        for line, title in line_names.items():
            if title == "Pet - " + demon:
                demon_of_line[line] = demon
    for r in read_csv(folder, "CreatureFamily"):
        for key in ("SkillLine_0", "SkillLine_1"):
            demon = demon_of_line.get(r.get(key, ""))
            if demon:
                families[demon].add(int(r["ID"]))

    # Every demon spell: (demon, name, rank) and whether the demon starts with it.
    spells = {}
    for r in read_csv(folder, "SkillLineAbility"):
        demon = demon_of_line.get(r["SkillLine"])
        name = names.get(r["Spell"], "")
        if not demon or not name or "(DND)" in name or name.endswith(" Effect"):
            continue
        if name in ("Warlock Pet Scaling",):
            continue
        spells[r["Spell"]] = (demon, name, rank_of(subtext.get(r["Spell"])),
                              r["AcquireMethod"] == STARTS_WITH)

    # Grimoires: item -> use spell -> the pet spell it teaches.
    teaches = {}
    for r in read_csv(folder, "SpellEffect"):
        if r["Effect"] == str(LEARN_PET_SPELL) and r["EffectTriggerSpell"] not in ("", "0"):
            teaches[r["SpellID"]] = r["EffectTriggerSpell"]
    effect_spell = {r["ID"]: r["SpellID"] for r in read_csv(folder, "ItemEffect")}
    item_effects = collections.defaultdict(list)
    for r in read_csv(folder, "ItemXItemEffect"):
        item_effects[r["ItemID"]].append(r["ItemEffectID"])
    books = {}
    for r in read_csv(folder, "ItemSparse"):
        if not r.get("Display_lang", "").startswith("Grimoire of"):
            continue
        for effect in item_effects.get(r["ID"], []):
            pet_spell = teaches.get(effect_spell.get(effect, ""))
            if pet_spell in spells:
                books[pet_spell] = (int(r["ID"]), int(r["RequiredLevel"] or 0), int(r["BuyPrice"] or 0))

    out = collections.defaultdict(lambda: collections.defaultdict(dict))
    for spell, (demon_name, name, rank, starts) in spells.items():
        row = {"spell": int(spell)}
        book = books.get(spell)
        if book:
            row["book"], row["level"], row["cost"] = book
        elif starts or rank == 1:
            row["free"] = True
        else:
            continue
        if rank in out[demon_name][name]:
            continue
        out[demon_name][name][rank] = row

    lines = [
        "-- Blackthornes Pets -- Data/DemonBooks.lua",
        "-- Every rank of every warlock demon's skills and the grimoire that",
        "-- teaches it.",
        "--",
        "-- Generated by tools/make_demon_books.py from the Forever client's game",
        "-- tables (build %s). Never edit it by hand: rerun the tool." % args.build,
        "--",
        "-- DEMONS[demon] = { families = { family id, ... }, skills = { [skill] =",
        "-- { [rank] = { spell (the demon's), book (the grimoire's item ID), level",
        "-- (the warlock's), cost (copper), free (the demon starts with it) } } } }.",
        "-- The Incubus shares the Succubus's skills.",
        "-- SPELLS[demon spell] = { skill, rank }.",
        "",
        "local _, ns = ...",
        "",
        "local DemonBooks = {}",
        "ns.DemonBooksData = DemonBooks",
        "",
        "DemonBooks.DEMONS = {",
    ]
    spell_lines = []
    for demon_name in sorted(out, key=lambda d: DEMONS.index(d)):
        lines.append("    [%s] = { families = { %s }, skills = {" % (
            lua_string(demon_name), ", ".join(str(f) for f in sorted(families[demon_name]))))
        for name in sorted(out[demon_name]):
            lines.append("        [%s] = {" % lua_string(name))
            for rank in sorted(out[demon_name][name]):
                row = out[demon_name][name][rank]
                if row.get("free"):
                    lines.append("            [%d] = { spell = %d, free = true }," % (rank, row["spell"]))
                else:
                    lines.append("            [%d] = { spell = %d, book = %d, level = %d, cost = %d }," % (
                        rank, row["spell"], row["book"], row["level"], row["cost"]))
                spell_lines.append((row["spell"], name, rank))
            lines.append("        },")
        lines.append("    } },")
    lines.append("}")
    lines.append("")
    lines.append("DemonBooks.SPELLS = {")
    for spell, name, rank in sorted(spell_lines):
        lines.append("    [%d] = { %s, %d }," % (spell, lua_string(name), rank))
    lines.append("}")
    (repo / "Data" / "DemonBooks.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote %d skills, %d ranks" % (sum(len(v) for v in out.values()), len(spell_lines)))


if __name__ == "__main__":
    main()
